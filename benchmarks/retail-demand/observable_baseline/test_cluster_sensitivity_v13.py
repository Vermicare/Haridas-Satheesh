"""Fictional negative controls for post-hoc store-cluster uncertainty.

No public retail scores are asserted or generated by these tests.
"""
import unittest

from cluster_sensitivity_v13 import store_cluster_bootstrap, evaluate_cluster_sensitivity
from retail_gate import EvidenceError
from test_official_holdout_v12 import fixture


class StoreClusterSensitivityTests(unittest.TestCase):
    def test_deterministic_order_independent_resampling(self):
        stats = [(7, 3, -0.3), (2, 2, 0.2), (9, 1, 0.1)]
        first = store_cluster_bootstrap(stats, reps=200)
        self.assertEqual(first, store_cluster_bootstrap(list(reversed(stats)), reps=200))
        self.assertAlmostEqual(first['series_weighted_macro_delta'], -0.4/6)
        self.assertEqual(first['scored_store_clusters'], 3)
        self.assertNotIn('store_id', first)

    def test_single_store_not_pseudoreplicated(self):
        with self.assertRaises(EvidenceError):
            store_cluster_bootstrap([(1, 100, -0.1)])

    def test_reject_duplicate_store_and_nonfinite(self):
        bad = [[(1, 1, 0.1), (1, 2, 0.2)],
               [(1, 1, float('nan')), (2, 1, 0.2)],
               [(1, True, 0.1), (2, 1, 0.2)],
               [(1, 0, 0.1), (2, 1, 0.2)],
               [(1, 1, float('inf')), (2, 1, 0.2)]]
        for stats in bad:
            with self.subTest(stats=stats), self.assertRaises(EvidenceError):
                store_cluster_bootstrap(stats)

    def test_invalid_bootstrap_config(self):
        for reps, seed in [(0, 3), (True, 3), (5, True), (-2, 4)]:
            with self.assertRaises(EvidenceError):
                store_cluster_bootstrap([(1, 1, 0.1), (2, 1, -0.2)], reps=reps, seed=seed)

    def test_two_store_fixture_matches_original_macro(self):
        tr1, ev1 = fixture((1, 3))
        tr2, ev2 = fixture((2,))
        for row in tr2 + ev2:
            row['store_id'] = 2
            row['product_id'] = 3
        report = evaluate_cluster_sensitivity([(1, 2), (2, 3)], tr1 + tr2, ev1 + ev2)
        self.assertEqual(report['scored_store_clusters'], 2)
        self.assertEqual(report['scored_series'], 2)
        self.assertEqual(report['unscored_store_clusters'], 0)
        self.assertAlmostEqual(report['series_weighted_macro_delta'], report['frozen_v12_series_macro_delta'])
        self.assertEqual(report['frozen_v12_scored_days'], 11)
        self.assertNotIn('store_ids', report)

    def test_all_censored_store_does_not_inflate_clusters(self):
        tr1, ev1 = fixture()
        tr2, ev2 = fixture(tuple(range(7)))
        for row in tr2 + ev2:
            row['store_id'] = 2
            row['product_id'] = 3
        with self.assertRaises(EvidenceError):
            evaluate_cluster_sensitivity([(1, 2), (2, 3)], tr1 + tr2, ev1 + ev2)

    def test_missing_eval_date_fails_closed(self):
        tr1, ev1 = fixture()
        tr2, ev2 = fixture()
        for row in tr2 + ev2:
            row['store_id'] = 2
            row['product_id'] = 3
        with self.assertRaises(EvidenceError):
            evaluate_cluster_sensitivity([(1, 2), (2, 3)], tr1 + tr2, ev1 + ev2[:-1])


if __name__ == '__main__':
    unittest.main()
